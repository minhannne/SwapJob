// Dịch thông báo theo ngôn ngữ đang chọn.
// Thông báo chưa có bản dịch sẽ hiển thị nội dung nhận được.
export function translateMessage(message: string, language: Language) {
  const key = serverMessageKeys[message] ?? message

  if (Object.prototype.hasOwnProperty.call(translations[language], key)) {
    return translations[language][key as TranslationKey]
  }

  return message
}

type LanguageContextValue = {
  language: Language
  locale: 'vi-VN' | 'en-GB'
  setLanguage: (language: Language) => void
  t: (key: TranslationKey) => string
}

export const LanguageContext = createContext<LanguageContextValue | null>(null)

export function useLanguage() {
  const context = useContext(LanguageContext)

  if (!context) {
    throw new Error('useLanguage requires LanguageProvider')
  }

  return context
}